# wireshark
# --------------------------------------------------------------------------


_COLOUR = {
    Severity.CRITICAL: ("[0,0,0]", "[65535,0,0]"),
    Severity.HIGH: ("[0,0,0]", "[65535,32768,0]"),
    Severity.MEDIUM: ("[0,0,0]", "[65535,65535,0]"),
    Severity.LOW: ("[0,0,0]", "[49151,65535,49151]"),
    Severity.INFO: ("[0,0,0]", "[57343,57343,57343]"),
}


def write_wireshark(path: Path, findings: Sequence[Finding]) -> int:
    """A Wireshark `colorfilters` file, one rule per finding.

    This is the cheap integration tier and it is worth almost all of the
    demo value: drop the file into the Wireshark profile directory and every
    flagged flow is highlighted in the GUI, with no plugin, no Lua, and no
    dissector API. A real plugin only becomes worth building if someone asks
    — Lua dissectors run per-packet and streaming, which is structurally
    wrong for flow-level analysis.
    """
    lines = ["# generated by tid-semantiQ", ""]
    written = 0
    for finding in findings:
        if not finding.display_filter:
            continue
        fg, bg = _COLOUR.get(finding.severity, _COLOUR[Severity.INFO])
        name = f"semantiq_{finding.rule_id}_{finding.channel.fingerprint}"
        lines.append(f'@{name}@{finding.display_filter}@{fg}{bg}')
        written += 1
    path.write_text("\n".join(lines) + "\n")
    return written


def write_filters(path: Path, findings: Sequence[Finding]) -> None:
    """Plain display filters, one per line, for pasting into the filter bar."""
    lines = []
    for finding in findings:
        if finding.display_filter:
            lines.append(f"# {finding.title} ({finding.confidence:.2f})")
            lines.append(finding.display_filter)
    path.write_text("\n".join(lines) + "\n")


