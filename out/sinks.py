_SEVERITY_TO_SOC = {
    Severity.CRITICAL: "critical",
    Severity.HIGH: "high",
    Severity.MEDIUM: "medium",
    Severity.LOW: "low",
    Severity.INFO: "info",
}


def soc_event(finding: Finding, host: str) -> Mapping[str, object]:
    """Shape a Finding as a tid-soc-agent collector event.

    Field names follow the SOC's existing event schema so the correlation
    consumer, Sigma engine and ATT&CK enrichment work on these without
    changes, and tid-AGENT can investigate them like any other telemetry.

    VERIFY BEFORE SHIPPING: the schema here is written from reading
    `endpoint/collector.py` and `services/ingest_api.py`, not from a
    published contract. Confirm against the live ingest API before trusting
    the integration — a silently-rejected batch looks exactly like a quiet
    network.

    The flow-sourced `period_s` and `interval_mad_s` are the point of the
    integration: they replace the connection-poll timing that makes the SOC's
    own beacon heuristic fire on persistent connections and miss short
    callbacks.
    """
    channel = finding.channel
    periodicity = finding.evidence.by_name("periodicity")
    rarity = finding.evidence.by_name("rarity")

    details = {
        "remote_ip": channel.responder.value if channel.responder else None,
        "remote_port": int(channel.dims.get("dport", 0) or 0),
        "local_ip": channel.initiator.value if channel.initiator else None,
        "channel_id": channel.fingerprint,
        "confidence": round(finding.confidence, 4),
        "rule_id": finding.rule_id,
        "display_filter": finding.display_filter,
        "sni": channel.dims.get("sni"),
        "source": "tid-semantiQ",
    }
    if periodicity:
        details["period_s"] = round(periodicity.features.get("period_s", 0.0), 2)
        details["interval_mad_s"] = round(periodicity.features.get("interval_mad_s", 0.0), 2)
        details["observations"] = int(periodicity.features.get("observations", 0))
    if rarity:
        details["prevalence"] = round(rarity.features.get("prevalence", 0.0), 5)

    tags = ["semantiq", channel.domain]
    if finding.rule_id.startswith("net.beacon"):
        tags += ["beacon_pattern", "c2_suspected"]
    if finding.rule_id.startswith("net.exfil"):
        tags.append("exfiltration_suspected")
    if finding.rule_id.startswith("dns.tunnel"):
        tags += ["dns_tunnel_suspected", "exfiltration_suspected"]

    return {
        "host": host,
        "agent": "tid-semantiQ",
        "category": "network",
        "subtype": finding.rule_id,
        "severity": _SEVERITY_TO_SOC[finding.severity],
        "title": finding.title,
        "description": _describe(finding),
        "tags": tags,
        "timestamp": finding.evidence.window[1],
        "details": details,
        # The full arithmetic trail rides along so the SOC stores how the
        # number was reached, not only the number.
        "evidence": finding.evidence.to_ledger(),
    }


def _describe(finding: Finding) -> str:
    periodicity = finding.evidence.by_name("periodicity")
    rarity = finding.evidence.by_name("rarity")
    bits = [finding.title]
    if periodicity:
        bits.append(
            f"period {periodicity.features.get('period_s', 0):.1f}s "
            f"(MAD {periodicity.features.get('interval_mad_s', 0):.1f}s) "
            f"over {periodicity.features.get('observations', 0):.0f} observations"
        )
    if rarity:
        bits.append(f"prevalence {rarity.features.get('prevalence', 0):.2%} of hosts")
    return "; ".join(bits)


def ship_to_soc(
    url: str,
    api_key: str,
    findings: Sequence[Finding],
    host: str,
    timeout: float = 10.0,
) -> int:
    """POST findings to the SOC's collector endpoint. Returns events accepted.

    urllib rather than requests, so standalone mode stays dependency-free.
    Raises on transport failure instead of swallowing it: a sink that fails
    quietly is worse than no sink, because the operator believes the findings
    arrived.
    """
    events = [soc_event(f, host) for f in findings]
    if not events:
        return 0

    payload = json.dumps({"events": events}).encode()
    request = urllib.request.Request(
        url,
        data=payload,
        headers={
            "Content-Type": "application/json",
            "X-API-Key": api_key,
        },
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=timeout) as response:
        if response.status >= 300:
            raise RuntimeError(f"SOC ingest returned {response.status}")
    return len(events)
