"""Output sinks: json, wireshark, soc.

This module is the whole reason tid-semantiQ is a standalone tool rather than
a module of tid-soc-agent. The engine is stateless and the SOC is one sink
among several — so `semantiq read foo.pcap` works on a laptop in a hotel room
with no Postgres, no dashboard and no auth, and the same findings ship into
the SOC with `--out soc`. The SOC is never a dependency.
"""

from __future__ import annotations

import json
import urllib.error
import urllib.request
from pathlib import Path
from typing import Mapping, Sequence

from core.model import Evidence, Finding, Severity

__all__ = ["write_json", "write_wireshark", "ship_to_soc", "soc_event"]


# --------------------------------------------------------------------------
# json
# --------------------------------------------------------------------------


def write_json(
    path: Path,
    findings: Sequence[Finding],
    evidences: Sequence[Evidence],
    redactor=None,
    inventory=None,
) -> None:
    """Findings plus the measurements for EVERY channel, including the ones
    that produced nothing.

    Emitting the silent channels matters: "no findings" backed by a thousand
    scored channels is a different claim from "no findings" because the
    parser dropped the traffic, and the operator cannot tell them apart from
    a report alone.

    Redaction defaults ON. This file is the one most likely to be attached to
    a bug report, and it is where the extracted tokens and cookies would
    otherwise be written in plain text.
    """
    if redactor is None:
        from core.redact import redact_secrets
        redactor = redact_secrets
    path.write_text(
        json.dumps(
            {
                "findings": [f.to_json(redactor=redactor) for f in findings],
                "channels": [e.to_ledger(redactor=redactor) for e in evidences],
                "inventory": inventory.to_json() if inventory else None,
            },
            indent=2,
        )
    )


